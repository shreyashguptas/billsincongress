/**
 * The Worker entry point: the OpenNext Worker, with signed-out pages served
 * from Cloudflare's edge cache. `wrangler.jsonc` points `main` here.
 *
 * A Worker on a Custom Domain runs in front of Cloudflare's cache, so nothing
 * the app returns is cached unless the Worker stores it. This file does that,
 * for exactly the requests `lib/edge-cache.ts` allows and the responses the
 * app itself marked `public, s-maxage=…`. Everything else goes straight to
 * OpenNext, untouched, as it did before.
 *
 * `x-edge-cache: HIT | MISS` on a response says which happened. Requests the
 * cache does not handle carry no such header.
 */
import { edgeCacheKey, isStorableResponse, sharedMaxAge } from './lib/edge-cache';
// @ts-ignore `.open-next/worker.js` is generated by `opennextjs-cloudflare build`.
import { default as openNext } from './.open-next/worker.js';

// The Durable Object classes OpenNext's Worker exports. Unused today (the
// queue and tag cache are KV and in-memory, open-next.config.ts), but the
// generated Worker exports them and wrangler expects the entry point to.
// @ts-ignore `.open-next/worker.js` is generated by `opennextjs-cloudflare build`.
export { DOQueueHandler, DOShardedTagCache, BucketCachePurge } from './.open-next/worker.js';

interface Env {
  CF_VERSION_METADATA?: { id?: string };
  [binding: string]: unknown;
}

interface Ctx {
  waitUntil(promise: Promise<unknown>): void;
  passThroughOnException(): void;
}

/** Headers that hold the app's own values while a stored copy carries the cache's. */
const ORIGINAL_CACHE_CONTROL = 'x-edge-original-cache-control';
const ORIGINAL_VARY = 'x-edge-original-vary';

export default {
  async fetch(request: Request, env: Env, ctx: Ctx): Promise<Response> {
    const key = edgeCacheKey(request, env.CF_VERSION_METADATA?.id ?? '');
    if (!key) return openNext.fetch(request, env, ctx);

    const cache = (caches as unknown as { default: Cache }).default;
    const cached = await cache.match(key);
    if (cached) return restore(cached, 'HIT');

    const response: Response = await openNext.fetch(request, env, ctx);
    if (!isStorableResponse(response)) return response;

    // The stored copy states its lifetime as max-age, which the Cache API
    // honours, and drops Vary: the key already separates the variants it keys
    // on (the document, never an RSC payload). The app's own headers ride
    // along and are put back on every hit.
    const stored = new Response(response.clone().body, response);
    const cacheControl = response.headers.get('cache-control') ?? '';
    stored.headers.set(ORIGINAL_CACHE_CONTROL, cacheControl);
    const vary = response.headers.get('vary');
    if (vary) stored.headers.set(ORIGINAL_VARY, vary);
    stored.headers.delete('vary');
    stored.headers.set('cache-control', `public, max-age=${sharedMaxAge(cacheControl)}`);
    ctx.waitUntil(cache.put(key, stored));

    return label(response, 'MISS');
  },
};

/** A stored copy, with the app's own Cache-Control and Vary back in place. */
function restore(cached: Response, status: 'HIT'): Response {
  const response = new Response(cached.body, cached);
  const cacheControl = response.headers.get(ORIGINAL_CACHE_CONTROL);
  if (cacheControl) response.headers.set('cache-control', cacheControl);
  const vary = response.headers.get(ORIGINAL_VARY);
  if (vary) response.headers.set('vary', vary);
  response.headers.delete(ORIGINAL_CACHE_CONTROL);
  response.headers.delete(ORIGINAL_VARY);
  response.headers.set('x-edge-cache', status);
  return response;
}

function label(response: Response, status: 'MISS'): Response {
  const labelled = new Response(response.body, response);
  labelled.headers.set('x-edge-cache', status);
  return labelled;
}
